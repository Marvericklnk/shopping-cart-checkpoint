const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const html = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');
const dom = new JSDOM(html, { runScripts: 'outside-only' });
dom.window.eval(fs.readFileSync(path.join(__dirname, 'js/script.js'), 'utf8'));
const doc = dom.window.document;
const cards = [...doc.querySelectorAll('.card')];
const click = (i, action, times = 1) => {
  for (let n = 0; n < times; n++) cards[i].querySelector(`[data-action="${action}"] span`).click();
};
const total = () => doc.querySelector('.total').textContent;
assert.equal(total(), '0.00 $');
click(0, 'decrease');
assert.equal(cards[0].querySelector('.quantity').textContent, '0');
click(0, 'increase', 2);
click(1, 'increase', 3);
click(2, 'increase');
assert.equal(total(), '310.00 $');
click(0, 'like');
assert.equal(cards[0].querySelector('.like').getAttribute('aria-pressed'), 'true');
assert.equal(cards[0].querySelector('.like').classList.contains('is-liked'), true);
assert.equal(total(), '310.00 $');
click(0, 'like');
assert.equal(cards[0].querySelector('.like').getAttribute('aria-pressed'), 'false');
assert.equal(cards[0].querySelector('.like').classList.contains('is-liked'), false);
click(1, 'delete');
assert.equal(total(), '250.00 $');
assert.equal(doc.querySelectorAll('.list-products > .card-body').length, 2);
click(0, 'decrease');
assert.equal(total(), '150.00 $');
click(0, 'delete');
click(2, 'delete');
assert.equal(total(), '0.00 $');
assert.equal(doc.querySelectorAll('.card').length, 0);
assert.equal(doc.querySelector('.empty-cart').hidden, false);
console.log('Passed: quantity changes, zero boundary, independent products, nested-icon clicks, heart toggle, deletions, totals, and empty cart.');
